"""Write ``robot_newton.usd``: the custom quadruped with its collision APIs on the mesh prims, for Newton.

``robot.usd`` (the canonical asset the 2.x checkpoints were trained on) authors ``PhysicsCollisionAPI`` +
``PhysicsMeshCollisionAPI`` (``physics:approximation = convexDecomposition``) on the ``node_STL_BINARY_`` Xform above
each collision mesh (``configuration/robot_physics.usd``, ``over "colliders"``). Isaac Sim PhysX accepts that layout.
Newton's USD importer only builds shapes from Gprims, so it skips all 17 colliders ("CollisionAPI applied to an
unknown UsdGeomGPrim type") and the robot has no contacts (``docs/source/how-to/prepare_asset_for_newton.rst``:
apply ``UsdPhysics.CollisionAPI`` only to the intended collision geometry).

This script does not touch the existing files. It writes two small text layers next to them:

* ``configuration/robot_physics_newton.usd``: sublayers ``robot_physics.usd`` and, for every collider Xform, deletes
  the two APIs there and applies them to the Mesh prims below it, with ``physics:approximation = convexHull``
  (``--approximation``). The collider prototypes stay instanceable: the internal references ``</colliders/...>``
  resolve in this layer stack.
* ``robot_newton.usd``: sublayers ``robot.usd`` (joint-limit overrides, Sensor/Robot variants unchanged) and adds a
  ``Physics = "Newton"`` variant whose payload is ``robot_physics_newton.usd``, selected by default.

Why convex hulls: Newton maps ``convexDecomposition`` to CoACD, which splits the 17 meshes into 191 convex parts
(31 per hip, up to 4494 vertices per part) and halves the zero-action throughput at 1024 envs; ``convexHull`` gives
one hull of at most 64 vertices per body, and the calf tip, which carries the robot, moves by less than 3 mm (lowest
point at the default pose, Newton CPU import). PhysX keeps its own ``convexDecomposition`` through ``robot.usd``.

Everything else (bodies, masses, inertias, joints, drives, limits, collision meshes) is composed from the original
layers. ``--check`` verifies that: it compares every authored property of the composed ``/quadruped_robot`` subtree of
both assets and expects the only difference to be the moved collision APIs (and the approximation token).
``--newton`` also imports both assets with Newton's USD importer on the CPU, the way Isaac Lab builds a clone source,
and counts collision shapes per body.

Run from the project root (``pxr`` from the Isaac Lab env)::

    python scripts/make_newton_asset.py                    # (re)write the two layers, then --check
    python scripts/make_newton_asset.py --check            # only verify the existing files
    CUDA_VISIBLE_DEVICES= python scripts/make_newton_asset.py --check --newton   # + Newton import (CPU)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pxr import Sdf, Usd

PROJECT = Path(__file__).resolve().parents[1]
ASSET_DIR = PROJECT / "src" / "quadruped_lab" / "assets" / "data" / "robots" / "custom_quad"
ROBOT_USD = ASSET_DIR / "robot.usd"
PHYSICS_LAYER = ASSET_DIR / "configuration" / "robot_physics.usd"
NEWTON_PHYSICS_LAYER = ASSET_DIR / "configuration" / "robot_physics_newton.usd"
NEWTON_USD = ASSET_DIR / "robot_newton.usd"

COLLISION_APIS = ("PhysicsCollisionAPI", "PhysicsMeshCollisionAPI")
DEFAULT_APPROXIMATION = "convexHull"
"""``physics:approximation`` authored on the collision meshes of the Newton copy (``keep``: copy robot.usd's)."""
HEADER = (
    "Generated by scripts/make_newton_asset.py (do not edit by hand). Newton-compatible collision layout of {src}: "
    "the collision APIs sit on the Mesh prims instead of the node_STL_BINARY_ Xforms above them."
)


def _collider_xforms(stage: Usd.Stage, root: str = "/colliders") -> list[tuple[Sdf.Path, list[Sdf.Path], str | None]]:
    """Collider prims below ``root`` that carry the collision APIs but are not Gprims, with the Mesh prims below each.

    ``/colliders`` holds the sources of the instanceable ``<body>/collisions`` prims (internal references).
    """
    from pxr import Usd, UsdGeom, UsdPhysics

    found = []
    for prim in Usd.PrimRange(stage.GetPrimAtPath(root)):
        if not prim.HasAPI(UsdPhysics.CollisionAPI) or prim.IsA(UsdGeom.Gprim):
            continue
        meshes = [p for p in Usd.PrimRange(prim) if p.IsA(UsdGeom.Mesh)]
        if not meshes:
            raise RuntimeError(f"{prim.GetPath()}: collision API on a non-Gprim without Mesh descendants")
        approx = prim.GetAttribute("physics:approximation").Get() if prim.HasAPI(UsdPhysics.MeshCollisionAPI) else None
        found.append((prim.GetPath(), [m.GetPath() for m in meshes], approx))
    return found


def write_layers(approximation: str = DEFAULT_APPROXIMATION) -> None:
    """Write ``configuration/robot_physics_newton.usd`` and ``robot_newton.usd`` (the existing files are untouched)."""
    from pxr import Sdf, Usd

    # the collider prototypes live under /colliders of the physics layer stack (robot_physics.usd + robot_base.usd)
    colliders = _collider_xforms(Usd.Stage.Open(str(PHYSICS_LAYER), load=Usd.Stage.LoadAll))
    if len(colliders) != 17:
        raise RuntimeError(f"expected 17 collider Xforms in {PHYSICS_LAYER.name}, found {len(colliders)}")

    physics = Sdf.Layer.CreateAnonymous(".usda")
    physics.comment = HEADER.format(src="configuration/robot_physics.usd")
    physics.defaultPrim = "quadruped_robot"
    physics.subLayerPaths.append("./robot_physics.usd")
    physics.pseudoRoot.SetInfo("metersPerUnit", 1.0)
    physics.pseudoRoot.SetInfo("upAxis", "Z")
    for xform_path, mesh_paths, approx in colliders:
        spec = Sdf.CreatePrimInLayer(physics, xform_path)
        spec.specifier = Sdf.SpecifierOver
        spec.SetInfo("apiSchemas", Sdf.TokenListOp.Create(deletedItems=list(COLLISION_APIS)))
        for mesh_path in mesh_paths:
            mspec = Sdf.CreatePrimInLayer(physics, mesh_path)
            mspec.specifier = Sdf.SpecifierOver
            mspec.SetInfo("apiSchemas", Sdf.TokenListOp.Create(prependedItems=list(COLLISION_APIS)))
            attr = Sdf.AttributeSpec(mspec, "physics:approximation", Sdf.ValueTypeNames.Token, Sdf.VariabilityUniform)
            attr.default = (approx or "none") if approximation == "keep" else approximation
    # Sdf.CreatePrimInLayer authors the ancestors as "over" already
    physics.Export(str(NEWTON_PHYSICS_LAYER), args={"format": "usda"})

    root = Sdf.Layer.CreateAnonymous(".usda")
    root.comment = HEADER.format(src="robot.usd")
    root.defaultPrim = "quadruped_robot"
    root.subLayerPaths.append("./robot.usd")
    root.pseudoRoot.SetInfo("metersPerUnit", 1.0)
    root.pseudoRoot.SetInfo("upAxis", "Z")
    robot = Sdf.PrimSpec(root.pseudoRoot, "quadruped_robot", Sdf.SpecifierOver)
    robot.SetInfo("variantSetNames", Sdf.StringListOp.Create(prependedItems=["Physics"]))
    robot.variantSelections["Physics"] = "Newton"
    vset = Sdf.VariantSetSpec(robot, "Physics")
    variant = Sdf.VariantSpec(vset, "Newton")
    variant.primSpec.payloadList.Prepend(Sdf.Payload("./configuration/robot_physics_newton.usd"))
    root.Export(str(NEWTON_USD), args={"format": "usda"})
    written = f"{NEWTON_PHYSICS_LAYER.relative_to(PROJECT)} ({len(colliders)} colliders)"
    print(f"wrote {written} and {NEWTON_USD.relative_to(PROJECT)}")


def _authored(stage: Usd.Stage, root: str = "/quadruped_robot") -> dict[str, tuple]:
    """{prim path: (type, applied schemas, {property: value})} of the composed subtree (instance proxies included).

    Array values (points, indices, ...) are compared by length and an md5 of their bytes, everything else by value.
    """
    import hashlib

    import numpy as np
    from pxr import Usd

    out = {}
    for prim in Usd.PrimRange(stage.GetPrimAtPath(root), Usd.TraverseInstanceProxies()):
        props = {}
        for prop in prim.GetAuthoredProperties():
            if hasattr(prop, "GetTargets"):
                props[prop.GetName()] = tuple(str(t) for t in prop.GetTargets())
                continue
            value = prop.Get()
            if type(value).__module__.startswith("pxr.Vt"):
                value = ("array", len(value), hashlib.md5(np.asarray(value).tobytes()).hexdigest())
            props[prop.GetName()] = value
        out[str(prim.GetPath())] = (prim.GetTypeName(), tuple(prim.GetAppliedSchemas()), props)
    return out


def check(approximation: str = DEFAULT_APPROXIMATION) -> int:
    """Verify that robot_newton.usd differs from robot.usd only in the moved collision APIs; 0 if it does."""
    from pxr import Usd, UsdGeom, UsdPhysics

    old = Usd.Stage.Open(str(ROBOT_USD), load=Usd.Stage.LoadAll)
    new = Usd.Stage.Open(str(NEWTON_USD), load=Usd.Stage.LoadAll)
    problems = []
    if new.GetDefaultPrim().GetName() != "quadruped_robot":
        problems.append("robot_newton.usd: default prim is not quadruped_robot")
    sel = new.GetDefaultPrim().GetVariantSet("Physics").GetVariantSelection()
    if sel != "Newton":
        problems.append(f"robot_newton.usd: Physics variant is {sel!r}, expected 'Newton'")

    def colliders(stage: Usd.Stage) -> tuple[list[Usd.Prim], list[Usd.Prim]]:
        on_gprims, on_others = [], []
        for prim in Usd.PrimRange(stage.GetPrimAtPath("/quadruped_robot"), Usd.TraverseInstanceProxies()):
            if prim.HasAPI(UsdPhysics.CollisionAPI):
                (on_gprims if prim.IsA(UsdGeom.Gprim) else on_others).append(prim)
        return on_gprims, on_others

    old_g, old_x = colliders(old)
    new_g, new_x = colliders(new)
    print(f"robot.usd:        collision APIs on {len(old_g)} Gprims, {len(old_x)} non-Gprims")
    print(f"robot_newton.usd: collision APIs on {len(new_g)} Gprims, {len(new_x)} non-Gprims")
    if new_x or len(new_g) != len(old_x) + len(old_g):
        problems.append("robot_newton.usd still has collision APIs on non-Gprims or lost colliders")
    approx_new = {str(p.GetPath().GetParentPath()): p.GetAttribute("physics:approximation").Get() for p in new_g}
    approx_old = {str(p.GetPath()): p.GetAttribute("physics:approximation").Get() for p in old_x}
    expected = approx_old if approximation == "keep" else dict.fromkeys(approx_old, approximation)
    if approx_new != expected:
        problems.append(f"approximation: expected {expected}, found {approx_new}")
    old_set, new_set = sorted(set(approx_old.values())), sorted(set(approx_new.values()))
    print(f"approximation: robot.usd {old_set} -> robot_newton.usd {new_set}")

    a, b = _authored(old), _authored(new)
    if set(a) != set(b):
        only_old, only_new = sorted(set(a) - set(b))[:5], sorted(set(b) - set(a))[:5]
        problems.append(f"prim sets differ: only in robot.usd {only_old}, only in robot_newton.usd {only_new}")
    moved = {str(p.GetPath()) for p in old_x} | {str(p.GetPath()) for p in new_g}
    for path in sorted(set(a) & set(b)):
        ta, sa, pa = a[path]
        tb, sb, pb = b[path]
        if path in moved:
            sa = tuple(s for s in sa if s not in COLLISION_APIS)
            sb = tuple(s for s in sb if s not in COLLISION_APIS)
            pb = {k: v for k, v in pb.items() if k != "physics:approximation" or k in pa}
        if (ta, sa, pa) != (tb, sb, pb):
            diff = {k: (pa.get(k), pb.get(k)) for k in set(pa) | set(pb) if pa.get(k) != pb.get(k)}
            problems.append(f"{path}: type/schemas/properties differ {ta, tb, sa, sb, diff}")
    print(f"compared {len(a)} composed prims; only the collision APIs of {len(old_x)} colliders moved to their meshes")
    return _report(problems)


def _report(problems: list[str]) -> int:
    """Print the problems and the verdict; 0 without problems, 1 otherwise."""
    for p in problems:
        print("PROBLEM:", p, file=sys.stderr)
    print("Newton asset OK" if not problems else "Newton asset check FAILED")
    return 0 if not problems else 1


def newton_collision_shapes(usd_path: Path) -> dict[str, int]:
    """Collision shapes per body when Newton's USD importer loads ``usd_path`` like an Isaac Lab clone source.

    Same call as ``isaaclab_newton/cloner/newton_clone_utils.py:build_source_builders`` (``add_usd`` with mesh
    approximation and the Newton / PhysX / MuJoCo schema resolvers of ``NewtonManager``). Runs on the CPU.
    """
    import newton
    from newton.usd import SchemaResolverMjc, SchemaResolverNewton, SchemaResolverPhysx
    from pxr import Usd

    stage = Usd.Stage.Open(str(usd_path), load=Usd.Stage.LoadAll)
    builder = newton.ModelBuilder()
    builder.add_usd(
        stage,
        root_path="/" + stage.GetDefaultPrim().GetName(),
        load_visual_shapes=False,
        hide_collision_shapes=True,
        skip_mesh_approximation=False,
        schema_resolvers=[SchemaResolverNewton(), SchemaResolverPhysx(), SchemaResolverMjc()],
    )
    shapes = dict.fromkeys((label.split("/")[-1] for label in builder.body_label), 0)
    for s in range(builder.shape_count):
        if builder.shape_flags[s] & newton.ShapeFlags.COLLIDE_SHAPES and builder.shape_body[s] >= 0:
            shapes[builder.body_label[builder.shape_body[s]].split("/")[-1]] += 1
    return shapes


def newton_check() -> int:
    """Import both assets with Newton (CPU) and check that every body of robot_newton.usd has a collider."""
    problems = []
    for path in (ROBOT_USD, NEWTON_USD):
        shapes = newton_collision_shapes(path)
        n, bodies = sum(shapes.values()), sum(1 for v in shapes.values() if v)
        print(f"{path.name}: {n} collision shapes on {bodies} bodies (of {len(shapes)})")
        if path == NEWTON_USD and bodies != len(shapes):
            problems.append(f"{path.name}: bodies without a collision shape: {[b for b, v in shapes.items() if not v]}")
    return _report(problems)


def main(argv: list[str] | None = None) -> int:
    """Write the Newton layers (unless ``--check``), verify them and optionally import them with Newton."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="only verify the existing robot_newton.usd")
    parser.add_argument(
        "--approximation",
        default=DEFAULT_APPROXIMATION,
        help="physics:approximation of the Newton colliders (default %(default)s; 'keep' copies robot.usd's)",
    )
    parser.add_argument("--newton", action="store_true", help="also import both assets with Newton (CPU)")
    args = parser.parse_args(argv)
    if not args.check:
        write_layers(args.approximation)
    rc = check(args.approximation)
    if args.newton:
        rc |= newton_check()
    return rc


if __name__ == "__main__":
    sys.exit(main())
